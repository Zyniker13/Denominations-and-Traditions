#!/usr/bin/env python3
"""Build INDEX.md, the master index of the repository, from catalog.yaml.

The index lists every confessional document (in the repository or not), the
collections of other source texts, and the studies, and shows which studies
cover which documents. For each study marked `tracked: true` it lists the
confessions the study does not yet cover, so that adding a confession shows
at once which studies need updating.

It also checks the catalog against the files: a catalogued path that does
not exist is an error, and a Markdown file under confessions/ that the
catalog does not list is reported in the index, so a confession added
without a catalog entry cannot go unnoticed.

Usage: python3 tools/build_index.py
"""
import os
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CATALOG = os.path.join(ROOT, "catalog.yaml")
OUT = os.path.join(ROOT, "INDEX.md")
CONFESSIONAL_KINDS = {"confession", "catechism", "creed"}
KIND_TITLES = {
    "confession": "confession",
    "catechism": "catechism",
    "creed": "creed",
    "church-order": "church order",
    "companion": "companion",
}


def link(title, path):
    return f"[{title}]({path})" if path else title


def expand_covers(study, documents):
    covered = set()
    for item in study.get("covers") or []:
        if item == "all-confessions":
            covered |= {d["id"] for d in documents
                        if d["kind"] in CONFESSIONAL_KINDS and d.get("path")}
        else:
            covered.add(item)
    return covered


def uncatalogued(documents):
    known = {d["path"] for d in documents if d.get("path")}
    found = []
    for dirpath, _, files in os.walk(os.path.join(ROOT, "confessions")):
        for name in files:
            if name.endswith(".md") and name != "README.md":
                rel = os.path.relpath(os.path.join(dirpath, name), ROOT)
                if rel not in known:
                    found.append(rel)
    return sorted(found)


def main():
    with open(CATALOG, encoding="utf-8") as f:
        catalog = yaml.safe_load(f)
    documents = catalog["documents"]
    collections = catalog.get("collections") or []
    studies = catalog.get("studies") or []
    by_id = {d["id"]: d for d in documents}

    errors = []
    for d in documents:
        if d.get("path") and not os.path.exists(os.path.join(ROOT, d["path"])):
            errors.append(f"{d['id']}: no file at {d['path']}")
    for c in collections:
        if not os.path.exists(os.path.join(ROOT, c["path"])):
            errors.append(f"{c['id']}: no file at {c['path']}")
    for s in studies:
        if not os.path.exists(os.path.join(ROOT, s["path"])):
            errors.append(f"{s['id']}: no file at {s['path']}")
        for item in (s.get("covers") or []) + (s.get("also") or []):
            if item != "all-confessions" and item not in by_id:
                errors.append(f"{s['id']}: unknown document id {item}")
    if errors:
        sys.exit("catalog.yaml errors:\n  " + "\n  ".join(errors))

    covers = {s["id"]: expand_covers(s, documents) for s in studies}
    also = {s["id"]: set(s.get("also") or []) for s in studies}
    tracked = [s for s in studies if s.get("tracked")]

    out = []
    w = out.append
    w("# Index")
    w("")
    w("> **Generated** by `tools/build_index.py` from [catalog.yaml](catalog.yaml).")
    w("> Edit the catalog and re-run the tool; do not edit this file by hand.")
    w("")
    w("Every confessional document, collection of source texts, and study in the")
    w("repository, with the studies that cover each document. When a confession is")
    w("added, the [coverage](#coverage) section shows which studies have not yet")
    w("taken it into account. How to add one is at the top of")
    w("[catalog.yaml](catalog.yaml).")
    w("")
    w("- [Confessional documents](#confessional-documents)")
    w("- [Collections](#collections)")
    w("- [Studies](#studies)")
    w("- [Coverage](#coverage)")
    w("- [Regenerating](#regenerating)")
    w("")

    w("## Confessional documents")
    w("")
    traditions = []
    for d in documents:
        if d["tradition"] not in traditions:
            traditions.append(d["tradition"])
    for tradition in traditions:
        w(f"### {tradition}")
        w("")
        w("| Document | Kind | Studied in |")
        w("| --- | --- | --- |")
        for d in documents:
            if d["tradition"] != tradition:
                continue
            title = link(d["title"], d.get("path"))
            if not d.get("path"):
                title += " *(not in the repository)*"
            studied = [link(s["id"], s["path"]) for s in studies
                       if d["id"] in covers[s["id"]] or d["id"] in also[s["id"]]]
            w(f"| {title} | {KIND_TITLES.get(d['kind'], d['kind'])} | {', '.join(studied) or '—'} |")
        w("")

    w("## Collections")
    w("")
    w("| Collection | Used by |")
    w("| --- | --- |")
    for c in collections:
        users = [link(s["id"], s["path"]) for s in studies if c["id"] in (s.get("collections") or [])]
        w(f"| {link(c['title'], c['path'])} | {', '.join(users) or '—'} |")
    w("")

    w("## Studies")
    w("")
    w("| Study | Id | What it covers |")
    w("| --- | --- | --- |")
    for s in studies:
        n = len(covers[s["id"]])
        scope = s.get("scope", "")
        extent = f"{n} document{'s' if n != 1 else ''} in the repository" if n else "no confessional documents"
        if also[s["id"]]:
            extent += f", {len(also[s['id']])} not in it"
        w(f"| {link(s['title'], s['path'])} | `{s['id']}` | {scope}{'. ' if scope else ''}{extent.capitalize()}. |")
    w("")

    w("## Coverage")
    w("")
    w("Studies marked `tracked` in the catalog are meant to cover every confession.")
    w("✓ means the study covers the document; ○ means it discusses a document")
    w("that is not in the repository; a blank means it does not cover it.")
    w("")
    confessional = [d for d in documents if d["kind"] in CONFESSIONAL_KINDS]
    w("| Document | " + " | ".join(f"`{s['id']}`" for s in tracked) + " |")
    w("| --- |" + " :---: |" * len(tracked))
    for d in confessional:
        cells = []
        for s in tracked:
            if d["id"] in covers[s["id"]]:
                cells.append("✓")
            elif d["id"] in also[s["id"]]:
                cells.append("○")
            else:
                cells.append("")
        name = d["title"] if d.get("path") else d["title"] + " *(not in the repository)*"
        w(f"| {name} | " + " | ".join(cells) + " |")
    w("")

    w("### Gaps")
    w("")
    any_gap = False
    for s in tracked:
        gaps = [d for d in confessional if d.get("path") and d["id"] not in covers[s["id"]]]
        if gaps:
            any_gap = True
            w(f"- [{s['title']}]({s['path']}) does not cover: "
              + "; ".join(link(d["title"], d["path"]) for d in gaps) + ".")
    if not any_gap:
        w("Every tracked study covers every confession in the repository.")
    w("")

    loose = uncatalogued(documents)
    if loose:
        w("### Files not in the catalog")
        w("")
        w("These files under `confessions/` have no entry in catalog.yaml. Add them so")
        w("that the studies' coverage can be tracked.")
        w("")
        for path in loose:
            w(f"- [{path}]({path})")
        w("")

    w("## Regenerating")
    w("")
    w("```")
    w("python3 tools/build_preservation.py   # passages and confessional citations")
    w("python3 tools/build_index.py          # this file")
    w("```")
    w("")

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print(f"wrote INDEX.md: {len(documents)} documents, {len(collections)} collections, "
          f"{len(studies)} studies; {len(loose)} uncatalogued files")


if __name__ == "__main__":
    main()
